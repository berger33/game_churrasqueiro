#!/usr/bin/env node
/**
 * Launcher icons for the Android playtest shell, rendered from the approved
 * store icon (`store-assets/icon/icon-1024.png`) so the app that lands on a
 * tester's home screen is the real game icon, not a placeholder.
 *
 * Writes into `android-shell/app/src/main/res/` (a source tree, so the outputs
 * are committed and a clone can build without running this).
 *
 * Legacy `ic_launcher`/`ic_launcher_round` at the five mipmap densities, plus the
 * adaptive foreground (`ic_launcher_foreground`, content held inside the 66/108
 * safe zone) that Android 8+ masks into whatever shape the launcher uses.
 *
 * Usage: node tools/android/make-android-icons.mjs
 */
import { createCanvas, loadImage } from '@napi-rs/canvas';
import { mkdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..', '..');
const SRC = join(ROOT, 'store-assets', 'icon', 'icon-1024.png');
const RES = join(ROOT, 'android-shell', 'app', 'src', 'main', 'res');

if (!existsSync(SRC)) {
  console.error(`[icons] missing ${SRC}`);
  process.exit(1);
}

/** mipmap density buckets and the sizes Android expects. */
const LEGACY = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
const ADAPTIVE = { mdpi: 108, hdpi: 162, xhdpi: 216, xxhdpi: 324, xxxhdpi: 432 };

const src = await loadImage(SRC);

function save(canvas, dir, file) {
  return mkdir(join(RES, dir), { recursive: true }).then(() =>
    writeFile(join(RES, dir, file), canvas.toBuffer('image/png'))
  );
}

/** Square, optionally circle-masked, drawn from the master at full bleed. */
function square(size, round) {
  const c = createCanvas(size, size);
  const ctx = c.getContext('2d');
  if (round) {
    ctx.beginPath();
    ctx.arc(size / 2, size / 2, size / 2, 0, Math.PI * 2);
    ctx.clip();
  }
  ctx.drawImage(src, 0, 0, size, size);
  return c;
}

/** Adaptive foreground: the art inside the 66/108 safe zone, rest transparent. */
function foreground(size) {
  const c = createCanvas(size, size);
  const ctx = c.getContext('2d');
  const inner = Math.round((size * 66) / 108);
  const off = Math.round((size - inner) / 2);
  ctx.drawImage(src, off, off, inner, inner);
  return c;
}

for (const [density, px] of Object.entries(LEGACY)) {
  await save(square(px, false), `mipmap-${density}`, 'ic_launcher.png');
  await save(square(px, true), `mipmap-${density}`, 'ic_launcher_round.png');
}
for (const [density, px] of Object.entries(ADAPTIVE)) {
  await save(foreground(px), `mipmap-${density}`, 'ic_launcher_foreground.png');
}

// The adaptive background is the icon's own corner colour, sampled so the mask
// never shows a seam between the art and the background plate.
const probe = createCanvas(8, 8);
const pctx = probe.getContext('2d');
pctx.drawImage(src, 0, 0, 8, 8);
const [r, g, b] = pctx.getImageData(1, 1, 1, 1).data;
const hex = `#${[r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('')}`;
await mkdir(join(RES, 'values'), { recursive: true });
await writeFile(
  join(RES, 'values', 'colors.xml'),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/android/make-android-icons.mjs from the approved store icon. -->
<resources>
  <color name="brasa_preto">#0A0705</color>
  <color name="icon_bg">${hex}</color>
</resources>
`
);

console.log(`[icons] ${Object.keys(LEGACY).length} legacy densities + ${Object.keys(ADAPTIVE).length} adaptive, background ${hex}`);
